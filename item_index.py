_PAREN_RE = re.compile(r"[（(]([^）)]*)[）)]")
QUERY_SYNONYMS = (
    ("高级会员", "高级账户"),
    ("会员", "账户"),
)


def _normalize(text: Any) -> str:
    value = unicodedata.normalize("NFKC", str(text or "")).lower().replace("ё", "е")
    return "".join(ch for ch in value if ch.isalnum() or "\u4e00" <= ch <= "\u9fff")


def _base_name(text: str) -> str:
    return re.split(r"[（(]", text, maxsplit=1)[0].strip()


def _aliases(item: dict[str, Any]) -> list[str]:
    zh = str(item.get("zh") or "").strip()
    en = str(item.get("en") or "").strip()
    ru = str(item.get("ru") or "").strip()
    values = [item.get("id", ""), en, ru, zh, _base_name(zh) if zh else ""]
    values.extend(_PAREN_RE.findall(zh))
    values.extend(_PAREN_RE.findall(en))
    # Some names contain a slash-separated alias ("X / Y").
    for value in list(values):
        if " / " in value:
            values.extend(part.strip() for part in value.split(" / "))
    normalized: list[str] = []
    seen: set[str] = set()
    for value in values:
        key = _normalize(value)
        if key and key not in seen:
            seen.add(key)
            normalized.append(key)
    return normalized


class ItemIndex:
    """Searchable ID ↔ English ↔ Russian ↔ Chinese item index."""

    def __init__(
        self,
        path: str | Path | None = None,
        overrides_path: str | Path | None = None,
        aliases_path: str | Path | None = None,
    ) -> None:
        self.path = Path(path) if path else Path(__file__).with_name("item_index.json")
        self.overrides_path = (
            Path(overrides_path)
            if overrides_path
            else self.path.with_name("item_name_overrides.json")
        )
        self.aliases_path = (
            Path(aliases_path)
            if aliases_path
            else self.path.with_name("item_aliases.json")
        )
        self.items: list[dict[str, Any]] = []
        self.by_id: dict[str, dict[str, Any]] = {}
        self.details: dict[str, Any] = {}
        self._alias_cache: dict[str, tuple[str, ...]] = {}
        self._alias_overrides: dict[str, list[str]] = {}
        self.generated_at = ""
        self._load_details()
        self._load()

    def _load_overrides(self) -> dict[str, str]:
        try:
            payload = json.loads(self.overrides_path.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            return {}
        if not isinstance(payload, dict):
            return {}
        return {
            str(item_id): str(name).strip()
            for item_id, name in payload.items()
            if isinstance(name, str) and name.strip()
        }

    def _load_alias_overrides(self) -> dict[str, list[str]]:
        """Load optional ``{item_id: ["alias", ...]}`` from the data directory."""
        try:
            payload = json.loads(self.aliases_path.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            return {}
        if not isinstance(payload, dict):
            return {}
        result: dict[str, list[str]] = {}
        for raw_id, raw_aliases in payload.items():
            item_id = str(raw_id).strip()
            if not item_id:
                continue
            values = [raw_aliases] if isinstance(raw_aliases, str) else raw_aliases
            if not isinstance(values, list):
                continue
            aliases: list[str] = []
            for value in values:
                text = str(value or "").strip()
                if text and len(text) <= 80 and text not in aliases:
                    aliases.append(text)
            if aliases:
                result[item_id] = aliases[:50]
        return result

    def _merge_aliases(
        self, item_id: str, aliases: list[str]
    ) -> tuple[str, ...]:
        merged = list(aliases)
        seen = set(merged)
        for raw in self._alias_overrides.get(item_id, []):
            normalized = _normalize(raw)
            if normalized and normalized not in seen:
                seen.add(normalized)
                merged.append(normalized)
        return tuple(merged)

    def _load(self) -> None:
        try:
            payload = json.loads(self.path.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            return
        raw_items = payload.get("items")
        if not isinstance(raw_items, list):
            return
        overrides = self._load_overrides()
        self._alias_overrides = self._load_alias_overrides()
        for raw in raw_items:
            if not isinstance(raw, dict) or not raw.get("id"):
                continue
            item_id = str(raw.get("id"))
            item = {
                "id": item_id,
                "en": str(raw.get("en") or "").strip(),
                "ru": str(raw.get("ru") or "").strip(),
                "zh": overrides.get(item_id, str(raw.get("zh") or "").strip()),
                "color": str(raw.get("color") or ""),
                "cat": str(raw.get("cat") or ""),
                "key": str(raw.get("key") or ""),
                "icon": str(raw.get("icon") or ""),
            }
            self.items.append(item)
            self.by_id[item["id"]] = item
            self._alias_cache[item_id] = self._merge_aliases(
                item_id, _aliases(item)
            )
        self.generated_at = str(payload.get("generated_at") or "")

    def _load_details(self) -> None:
        path = self.path.with_name("item_details.json")
        try:
            payload = json.loads(path.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            return
        raw = payload.get("details")
        if isinstance(raw, dict):
            self.details = {
                str(item_id): value
                for item_id, value in raw.items()
                if isinstance(value, dict)
            }

    def get_details(self, item_id: str) -> dict[str, Any]:
        return self.details.get(str(item_id or "").strip(), {})

    @property
    def ready(self) -> bool:
        return bool(self.items)

    def get(self, item_id: str) -> dict[str, Any] | None:
        return self.by_id.get(str(item_id or "").strip())

    def _aliases_for(self, item: dict[str, Any]) -> tuple[str, ...]:
        cached = self._alias_cache.get(str(item.get("id") or ""))
        return cached if cached is not None else tuple(_aliases(item))

    def search(self, query: str, *, limit: int = 8) -> list[dict[str, Any]]:
        q = _normalize(query)
        if not q or not self.items:
            return []

        terms = [q]
        for old, new in QUERY_SYNONYMS:
            for term in list(terms):
                if old in term:
                    variant = term.replace(old, new)
                    if variant not in terms:
                        terms.append(variant)
        single_cjk = len(q) == 1 and "\u4e00" <= q <= "\u9fff"
        exact: list[dict[str, Any]] = []
        contains: list[dict[str, Any]] = []
        fuzzy: list[tuple[float, dict[str, Any]]] = []
        fuzzy_enabled = any(len(term) >= 3 for term in terms)
        for item in self.items:
            aliases = self._aliases_for(item)
            if any(term in aliases for term in terms):
                exact.append(item)
                continue
            if any(
                term in alias
                for term in terms
                if len(term) >= 2 or single_cjk
                for alias in aliases
            ):
                contains.append(item)
                continue
            if fuzzy_enabled:
                score = 0.0
                item_id = _normalize(item.get("id"))
                for term in terms:
                    for alias in aliases:
                        # IDs are already handled by exact/contains matching;
                        # fuzzy-matching them adds unrelated short-ID noise
                        # (e.g. "m2k7" for "mk47").
                        if alias == item_id:
                            continue
                        total = len(term) + len(alias)
                        # SequenceMatcher's ratio can never exceed 2*min/total.
                        if total and 200 * min(len(term), len(alias)) < 72 * total:
                            continue
                        candidate = SequenceMatcher(None, term, alias).ratio()
                        if candidate > score:
                            score = candidate
                if score >= 0.72:
                    fuzzy.append((score, item))
            if (
                not single_cjk
                and len(exact) >= limit
                and len(contains) >= limit
            ):
                break

        def contains_rank(item: dict[str, Any]) -> tuple[int, int]:
            hits = [
                (0 if alias.startswith(term) else 1, len(alias))
                for term in terms
                for alias in self._aliases_for(item)
                if term in alias
            ]
            return min(hits) if hits else (2, 999)

        contains.sort(key=contains_rank)
        fuzzy.sort(key=lambda pair: pair[0], reverse=True)
        result: list[dict[str, Any]] = []
        seen: set[str] = set()
        for group in (exact, contains, [item for _, item in fuzzy]):
            for item in group:
                if item["id"] in seen:
                    continue
                seen.add(item["id"])
                result.append(item)
                if len(result) >= limit:
                    return result
        if not result and len(q) >= 2:
            prefix = q[:2]
            nearby: list[tuple[dict[str, Any], tuple[str, ...]]] = []
            for item in self.items:
                aliases = self._aliases_for(item)
                if any(alias.startswith(prefix) for alias in aliases):
                    nearby.append((item, aliases))
            nearby.sort(
                key=lambda pair: min(
                    (
                        (0 if alias.startswith(q) else 1, len(alias))
                        for alias in pair[1]
                        if alias.startswith(prefix)
                    ),
                    default=(2, 999),
                )
            )
            result = [item for item, _ in nearby[:limit]]
        return result

    def resolve(self, query: str) -> tuple[dict[str, Any] | None, list[dict[str, Any]]]:
        """Return (unique item or None, matches).

        A raw item ID always wins; otherwise an exact alias with one match wins.
        """
        raw = str(query or "").strip()
        if raw in self.by_id:
            return self.by_id[raw], [self.by_id[raw]]
        matches = self.search(raw, limit=20)
        if len(matches) == 1:
            return matches[0], matches
        if matches:
            q = _normalize(raw)
            english = [
                item
                for item in matches
                if q and q == _normalize(item.get("en"))
            ]
            if len(english) == 1:
                return english[0], matches
            if len(english) > 1:
                return None, matches
            # "冰霜" is an exact Chinese artifact name; don't turn it into
            # candidates just because other items contain the same substring.
            # Weapon bases are deferred so "x95" still prefers the base rifle.
            chinese_exact = [
                item
                for item in matches
                if q
                and q == _normalize(_base_name(str(item.get("zh") or "")))
                and not str(item.get("cat") or "").startswith("weapon/")
            ]
            if len(chinese_exact) == 1:
                return chinese_exact[0], matches
            # A short token can match a weapon, its parts and a skin
            # ("mk47" → MK47 Mutant / MK47 parts / Melted MK47). Do not hide
            # the skin by choosing the weapon; show candidates instead.
            categories = {
                str(item.get("cat") or "").split("/", 1)[0]
                for item in matches
            }
            if len(categories) > 1:
                return None, matches
            weapons = [
                item
                for item in matches
                if str(item.get("cat") or "").startswith("weapon/")
            ]
            # "x95" should resolve to "IWI Tavor X95" (the base weapon),
            # not to "X95 (A)" whose stripped base name is also "X95".
            # Skip very short tokens so "m4" offers candidates instead of
            # picking an arbitrary suffix match.
            suffix = [
                item
                for item in weapons
                if len(q) >= 3
                and q
                and _normalize(item.get("en")).endswith(q)
                and _normalize(item.get("en")) != q
                and not _PAREN_RE.search(str(item.get("en") or ""))
            ]
            if len(suffix) == 1:
                return suffix[0], matches
            chinese = [
                item
                for item in matches
                if q and q == _normalize(_base_name(str(item.get("zh") or "")))
            ]
            if len(chinese) == 1:
                return chinese[0], matches
            if len(chinese) > 1:
                return None, matches
            by_id = [item for item in matches if item.get("id") == raw]
            if len(by_id) == 1:
                return by_id[0], matches
        return None, matches


def category_label(category: str | None) -> str:
    value = str(category or "")
    if value in CATEGORY_LABELS:
        return CATEGORY_LABELS[value]
    top = value.split("/", 1)[0]
    return CATEGORY_LABELS.get(top, value or "未知类别")


def _looks_like_locale_key(value: str) -> bool:
    return bool(re.match(r"^[a-z][a-z0-9_]*(?:\.[a-z0-9_]+)+$", value or ""))


def display_translation(item: dict[str, Any]) -> str:
    zh = str(item.get("zh") or "").strip()
    en = str(item.get("en") or "").strip()
    if not zh or _looks_like_locale_key(zh):
        return ""
    if en and _normalize(en) in _normalize(zh):
        zh = _base_name(zh)
    if en and _normalize(zh) == _normalize(en):
        return ""
    return zh


def display_english(item: dict[str, Any]) -> str:
    en = str(item.get("en") or "").strip()
    if en and not _looks_like_locale_key(en):
        return en
    zh = str(item.get("zh") or "").strip()
    if zh and not _looks_like_locale_key(zh):
        return zh
    return str(item.get("id") or "未知物品")


def display_name(item: dict[str, Any]) -> str:
    zh = str(item.get("zh") or "").strip()
    en = str(item.get("en") or "").strip()
    if _looks_like_locale_key(zh):
        zh = ""
    if _looks_like_locale_key(en):
        en = ""
    if zh and en and _normalize(zh) != _normalize(en):
        shown_zh = _base_name(zh) if _normalize(en) in _normalize(zh) else zh
        return f"{shown_zh} / {en}"
    return zh or en or str(item.get("id") or "未知物品")
